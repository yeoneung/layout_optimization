"""
PPO for the improvement policy (Tracks A, C and D).

The same trainer covers all three because they differ only in environment
configuration:

    Track A  reward=best   accept=always      instances=fixed
    Track C  reward=best   accept=metropolis  instances=fixed     (learned proposal for SA)
    Track D  reward=best   accept=*           instances=random    (amortized over a brief distribution)

and the legacy formulation is recovered exactly with
    reward=delta  accept=always  ops=translate  gamma=0.995
so the ablation table is generated by the same code path as the headline runs.
"""

import argparse
import json
import os
import sys
import time

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import core                                              # noqa: E402
from improve_env import ImproveEnv, N_GLOB               # noqa: E402
from nets import ImprovePolicy, OP_TRANSLATE, OP_JUMP, OP_SWAP, OP_SNAP  # noqa: E402

OP_LOOKUP = {"translate": OP_TRANSLATE, "jump": OP_JUMP, "swap": OP_SWAP, "snap": OP_SNAP}


class RunningNorm:
    def __init__(self, dim):
        self.mean = np.zeros(dim, dtype=np.float64)
        self.var = np.ones(dim, dtype=np.float64)
        self.count = 1e-4

    def update(self, x):
        x = x.reshape(-1, x.shape[-1])
        bm, bv, bc = x.mean(0), x.var(0), x.shape[0]
        d = bm - self.mean
        tot = self.count + bc
        self.mean += d * bc / tot
        self.var = (self.var * self.count + bv * bc + d ** 2 * self.count * bc / tot) / tot
        self.count = tot

    def __call__(self, x):
        return np.clip((x - self.mean) / np.sqrt(self.var + 1e-8), -10, 10).astype(np.float32)

    def state(self):
        return {"mean": self.mean, "var": self.var, "count": self.count}

    def load(self, s):
        self.mean, self.var, self.count = s["mean"], s["var"], s["count"]


def make_env(args, seed, batch=None, horizon=None):
    """Fixed reference scenario, or a fresh draw from the instance distribution."""
    B = batch or args.n_envs
    H = horizon or args.horizon
    if args.instances == "fixed":
        from layout_env import build_spec
        spec = build_spec(args.scenario, flip_adj=args.flip_adj)
        inst = core.from_spec(spec, B)
        resample = None
    else:
        gen_rng = np.random.default_rng(seed + 999)
        inst = core.generate_instances(B, args.n_rooms, gen_rng)

        def resample(rng):
            return core.generate_instances(B, args.n_rooms, rng)

    return ImproveEnv(inst, horizon=H, seed=seed, action_mode=args.action_mode,
                      delta_max=args.delta_max, reward=args.reward, accept=args.accept,
                      resample=resample, soft_start=args.soft)


def to_dev(a, dev):
    return {k: torch.as_tensor(v, device=dev) for k, v in a.items()}


def train(args):
    dev = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    torch.manual_seed(args.seed)
    np.random.seed(args.seed)

    env = make_env(args, args.seed)
    ops = tuple(OP_LOOKUP[o] for o in args.ops.split(","))
    if env.lattice and OP_SNAP in ops:
        ops = tuple(o for o in ops if o != OP_SNAP)   # already on the lattice
    feat = env.obj.feat_dim
    n = env.n

    model = ImprovePolicy(feat, N_GLOB, d_model=args.d_model,
                          n_blocks=args.n_blocks, ops=ops).to(dev)
    opt = torch.optim.Adam(model.parameters(), lr=args.lr, eps=1e-5)
    norm = RunningNorm(feat)

    obs, glob = env.reset()
    norm.update(obs)
    n_iters = max(1, args.total_steps // (args.n_envs * args.rollout))
    history, t_start = [], time.time()
    print(f"[{args.tag}] ops={[o for o in args.ops.split(',')]} mode={args.action_mode} "
          f"reward={args.reward} accept={args.accept} gamma={args.gamma} "
          f"instances={args.instances} -> {n_iters} iters", flush=True)

    for it in range(1, n_iters + 1):
        # soft-overlap curriculum: smooth early, exact for the last 40% of training
        env.soft = args.soft * max(0.0, 1.0 - it / (0.6 * n_iters))

        R = args.rollout
        b_obs = np.zeros((R, args.n_envs, n, feat), dtype=np.float32)
        b_glob = np.zeros((R, args.n_envs, N_GLOB), dtype=np.float32)
        b_act = {k: np.zeros((R, args.n_envs) + s, dtype=d)
                 for k, s, d in (("room", (), np.int64), ("op", (), np.int64),
                                 ("swap", (), np.int64), ("delta", (2,), np.float32),
                                 ("jump", (2,), np.float32))}
        b_logp = np.zeros((R, args.n_envs), dtype=np.float32)
        b_rew = np.zeros((R, args.n_envs), dtype=np.float32)
        b_val = np.zeros((R, args.n_envs), dtype=np.float32)
        b_done = np.zeros((R, args.n_envs), dtype=np.float32)
        ep_best, ep_feas, ep_ops = [], [], []

        for t in range(R):
            nobs = norm(obs)
            b_obs[t], b_glob[t] = nobs, glob
            with torch.no_grad():
                a = model.act(torch.as_tensor(nobs, device=dev),
                              torch.as_tensor(glob, device=dev))
            act_np = {k: a[k].cpu().numpy() for k in ("room", "op", "swap", "delta", "jump")}
            for k in b_act:
                b_act[k][t] = act_np[k]
            b_logp[t] = a["logp"].cpu().numpy()
            b_val[t] = a["value"].cpu().numpy()
            obs, glob, rew, done = env.step(act_np)
            norm.update(obs)
            b_rew[t] = rew
            b_done[t] = float(done)
            ep_ops.append(np.bincount(act_np["op"], minlength=4))
            if done:
                tot, c = env.exact_best()
                ep_best.append(tot / env.ceil)
                ep_feas.append((c["overlap_area"] <= 1e-9).astype(float))
                obs, glob = env.reset(new_instance=args.instances != "fixed")
                norm.update(obs)

        with torch.no_grad():
            last_val = model.act(torch.as_tensor(norm(obs), device=dev),
                                 torch.as_tensor(glob, device=dev))["value"].cpu().numpy()

        adv = np.zeros_like(b_rew)
        lastgae = 0.0
        for t in reversed(range(R)):
            nextval = last_val if t == R - 1 else b_val[t + 1]
            nonterm = 1.0 - b_done[t]
            delta = b_rew[t] + args.gamma * nextval * nonterm - b_val[t]
            lastgae = delta + args.gamma * args.lam * nonterm * lastgae
            adv[t] = lastgae
        ret = adv + b_val

        T = torch.as_tensor
        f_obs = T(b_obs.reshape(-1, n, feat), device=dev)
        f_glob = T(b_glob.reshape(-1, N_GLOB), device=dev)
        f_act = {k: T(v.reshape((-1,) + v.shape[2:]), device=dev) for k, v in b_act.items()}
        f_logp = T(b_logp.reshape(-1), device=dev)
        f_adv = T(adv.reshape(-1), device=dev)
        f_ret = T(ret.reshape(-1), device=dev)
        f_adv = (f_adv - f_adv.mean()) / (f_adv.std() + 1e-8)

        N = f_obs.shape[0]
        idx = np.arange(N)
        ent_coef = args.ent_coef * max(0.05, 1.0 - it / (0.8 * n_iters))
        for _ in range(args.epochs):
            np.random.shuffle(idx)
            for s in range(0, N, args.minibatch):
                mb = torch.as_tensor(idx[s:s + args.minibatch], device=dev)
                logp, ent, val = model.evaluate(
                    f_obs[mb], f_glob[mb], {k: v[mb] for k, v in f_act.items()})
                ratio = (logp - f_logp[mb]).exp()
                A = f_adv[mb]
                pi_loss = -torch.min(ratio * A,
                                     torch.clamp(ratio, 1 - args.clip, 1 + args.clip) * A).mean()
                v_loss = F.mse_loss(val, f_ret[mb])
                loss = pi_loss + args.vf_coef * v_loss - ent_coef * ent.mean()
                opt.zero_grad(set_to_none=True)
                loss.backward()
                nn.utils.clip_grad_norm_(model.parameters(), args.max_grad_norm)
                opt.step()

        if ep_best:
            opsum = np.sum(ep_ops, axis=0)
            rec = {"iter": it, "steps": it * args.n_envs * args.rollout,
                   "best_frac": float(np.mean(np.concatenate(ep_best))),
                   "feasible": float(np.mean(np.concatenate(ep_feas))),
                   "op_mix": (opsum / max(1, opsum.sum())).round(3).tolist(),
                   "elapsed": time.time() - t_start}
            history.append(rec)
            if it % args.log_every == 0 or it == n_iters:
                print(f"[{args.tag}] it {it}/{n_iters} steps={rec['steps']} "
                      f"J/ceil={rec['best_frac']:.4f} feas={rec['feasible']:.2f} "
                      f"ops={rec['op_mix']} ({rec['elapsed']:.0f}s)", flush=True)

    os.makedirs(args.out, exist_ok=True)
    path = os.path.join(args.out, f"{args.tag}.pt")
    torch.save({"model": model.state_dict(), "norm": norm.state(),
                "args": vars(args), "ops": list(ops)}, path)
    with open(os.path.join(args.out, f"{args.tag}_history.json"), "w") as f:
        json.dump(history, f, indent=1)
    print(f"[{args.tag}] saved {path}  ({time.time()-t_start:.0f}s)", flush=True)
    return path


def get_parser():
    p = argparse.ArgumentParser()
    p.add_argument("--tag", default="run")
    p.add_argument("--scenario", default="comb_high")
    p.add_argument("--flip-adj", dest="flip_adj", action="store_true", default=True)
    p.add_argument("--no-flip-adj", dest="flip_adj", action="store_false")
    p.add_argument("--instances", default="fixed", choices=["fixed", "random"])
    p.add_argument("--n-rooms", dest="n_rooms", type=int, default=32)
    p.add_argument("--action-mode", dest="action_mode", default="lattice",
                   choices=["lattice", "continuous"])
    p.add_argument("--ops", default="translate,jump,swap,snap")
    p.add_argument("--reward", default="best", choices=["best", "delta"])
    p.add_argument("--accept", default="always", choices=["always", "metropolis"])
    p.add_argument("--delta-max", dest="delta_max", type=float, default=3.0)
    p.add_argument("--soft", type=float, default=0.0,
                   help="initial weight of the smoothed objective (curriculum)")
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--total-steps", dest="total_steps", type=int, default=3_000_000)
    p.add_argument("--n-envs", dest="n_envs", type=int, default=128)
    p.add_argument("--rollout", type=int, default=64)
    p.add_argument("--horizon", type=int, default=512)
    p.add_argument("--gamma", type=float, default=1.0)
    p.add_argument("--lam", type=float, default=0.95)
    p.add_argument("--clip", type=float, default=0.2)
    p.add_argument("--epochs", type=int, default=4)
    p.add_argument("--minibatch", type=int, default=1024)
    p.add_argument("--lr", type=float, default=3e-4)
    p.add_argument("--ent-coef", dest="ent_coef", type=float, default=0.01)
    p.add_argument("--vf-coef", dest="vf_coef", type=float, default=0.5)
    p.add_argument("--max-grad-norm", dest="max_grad_norm", type=float, default=0.5)
    p.add_argument("--d-model", dest="d_model", type=int, default=128)
    p.add_argument("--n-blocks", dest="n_blocks", type=int, default=3)
    p.add_argument("--log-every", dest="log_every", type=int, default=10)
    p.add_argument("--out", default="runs")
    return p


if __name__ == "__main__":
    train(get_parser().parse_args())
